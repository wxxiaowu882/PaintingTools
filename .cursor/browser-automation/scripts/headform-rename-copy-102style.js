function plainToRich(text) {
  return text
    .split('\n')
    .map((line) => {
      const t = line.trim();
      if (
        /^【/.test(t) ||
        /^[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬]+[.–-]/.test(t) ||
        /^[①②③④⑤⑥⑦⑧⑨]+\./.test(t) ||
        /^\d+\./.test(t) ||
        /^[A-ZⒶⒷ]\./.test(t) ||
        /^[①②③④⑤⑥⑦⑧⑨]–[①②③④⑤⑥⑦⑧⑨]/.test(t) ||
        /^[①②③④⑤⑥⑦⑧⑨]→/.test(t)
      ) {
        return '<strong>' + line + '</strong>';
      }
      return line;
    })
    .join('<br>');
}

function loadByPrefix(prefix) {
  const f = fs.readdirSync(dir).find((n) => n.startsWith(prefix) && n.endsWith('.json'));
  if (!f) throw new Error('missing ' + prefix);
  const full = path.join(dir, f);
  return { f, full, data: JSON.parse(fs.readFileSync(full, 'utf8')) };
}

