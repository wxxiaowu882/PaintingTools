function newFileName(oldName, newDisplayName) {
  const m = oldName.match(/^(\d+[A-Za-z]?)_/);
  if (!m) throw new Error('bad old name ' + oldName);
  return m[1] + '_' + newDisplayName + '.json';
}

function applyOne(prefix) {
  const { f, full, data } = loadByPrefix(prefix);
  const cfg = COPY[prefix];
  if (!cfg) throw new Error('no cfg ' + prefix);

  data.name = cfg.name;
  data.meta = data.meta || {};
  data.meta.detail = cfg.detail;

  let kp;
  if (cfg.keepUserKeyPoints) {
    // 102：保留用户文案，只把「视角」字样在首句若需可不动；用户已写「正面视角的头部外轮廓」合适
    kp = String(data.meta.keyPoints || '');
    // 若仍含旧「【视角】」无关；确保无技术废话
  } else {
    kp = cfg.keyPoints;
  }
  data.meta.keyPoints = kp;
  data.meta.keyPointsRich = plainToRich(kp);

  const newName = newFileName(f, cfg.name);
  const newFull = path.join(dir, newName);
  fs.writeFileSync(newFull, JSON.stringify(data) + '\n');
  if (full !== newFull && fs.existsSync(full)) fs.unlinkSync(full);
  console.log(f, '→', newName);
}

const prefixes = Object.keys(COPY);
for (const p of prefixes) applyOne(p);

