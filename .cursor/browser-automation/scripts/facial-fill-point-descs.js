function normalizeName(text) {
  return String(text || '').trim();
}

function descFor(text) {
  const t = normalizeName(text);
  if (DESC[t]) return DESC[t];
  // soft aliases
  if (t.includes('白脊') && t.includes('下唇')) return DESC['白脊（下唇）'];
  if (t.includes('白脊')) return DESC['白脊（口唇外圈脊状隆起线）'];
  if (t === '鼻唇沟' || t.startsWith('鼻唇沟')) return DESC['鼻唇沟'];
  return null;
}

function main() {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  const report = [];
  for (const fn of files) {
    const fp = path.join(dir, fn);
    const data = JSON.parse(fs.readFileSync(fp, 'utf8'));
    const pts = data.pointsData || [];
    let filled = 0;
    let missing = [];
    for (const p of pts) {
      const d = descFor(p.text);
      if (!d) {
        missing.push({ id: p.id, text: p.text, type: p.type });
        continue;
      }
      if ((p.desc || '') !== d) {
        p.desc = d;
        filled++;
      } else if ((p.desc || '').trim()) {
        filled++;
      }
    }
    if (!dry) {
      fs.writeFileSync(fp, JSON.stringify(data, null, 2), 'utf8');
    }
    report.push({
      file: fn,
      points: pts.length,
      filled,
      missing,
      emptyAfter: pts.filter((p) => !(p.desc || '').trim()).length,
    });
  }
  console.log(JSON.stringify({ dry, report }, null, 2));
  const bad = report.some((r) => r.missing.length || r.emptyAfter);
  process.exit(bad ? 1 : 0);
}

main();
